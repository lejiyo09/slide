/**
 * 한국어 맞춤법 보조 규칙. hunspell 사전(형태소 단위)은 "되요", "할수있다"처럼 형태는 있지만 틀린 표현을 놓치므로,
 * 국립국어원 「한국어 어문 규범」과 '자주 틀리는 맞춤법'에서 흔한 것을 규칙으로 더한다.
 * 각 규칙: 찾을 정규식, 고칠 말(함수 가능), 이유.
 */

export interface KoRule {
  re: RegExp;
  fix: string | ((m: RegExpExecArray) => string);
  why: string;
}

/** 받침 ㄹ로 끝나는 음절인지 (할, 갈, 볼, 먹을 …) */
const rieulFinal = (ch: string) => {
  const c = ch.charCodeAt(0) - 0xac00;
  return c >= 0 && c < 11172 && c % 28 === 8;
};

export const KO_RULES: KoRule[] = [
  // 되/돼: '되어'의 준말은 '돼' (한글 맞춤법 제35항)
  { re: /되요/g, fix: '돼요', why: "'되어요'의 준말은 '돼요'입니다." },
  { re: /되서(?![가-힣])/g, fix: '돼서', why: "'되어서'의 준말은 '돼서'입니다." },
  { re: /됬/g, fix: '됐', why: "'되었'의 준말은 '됐'입니다." },
  { re: /안되(요|나요|죠|겠|서|니)/g, fix: (m) => `안 돼${m[1] === '요' ? '요' : m[1] === '겠' ? '겠' : m[1] === '서' ? '서' : m[1]}`, why: "'안'은 띄어 쓰고 '되어'의 준말은 '돼'입니다." },
  { re: /않되/g, fix: '안 돼', why: "부정 부사는 '안', '되어'의 준말은 '돼'입니다." },
  { re: /뵈요/g, fix: '봬요', why: "'뵈어요'의 준말은 '봬요'입니다." },
  // 어미
  { re: /([가-힣])께요/g, fix: (m) => (rieulFinal(m[1]) ? `${m[1]}게요` : m[0]), why: "어미 '-ㄹ게요'는 '-ㄹ께요'로 적지 않습니다 (제53항)." },
  { re: /([가-힣])께(?=[\s.,!?]|$)/g, fix: (m) => (rieulFinal(m[1]) ? `${m[1]}게` : m[0]), why: "어미 '-ㄹ게'는 '-ㄹ께'로 적지 않습니다 (제53항)." },
  { re: /([가-힣])읍니다/g, fix: (m) => `${m[1]}습니다`, why: "'-읍니다'가 아니라 '-습니다'입니다 (표준어 규정 제17항)." },
  { re: /(있|없)슴니다/g, fix: (m) => `${m[1]}습니다`, why: "'-습니다'로 적습니다." },
  // 의존 명사 띄어쓰기 (제42항): -ㄹ 수, -ㄹ 때, -는 것
  { re: /([가-힣])수(\s?)(있|없)/g, fix: (m) => (rieulFinal(m[1]) ? `${m[1]} 수 ${m[3]}` : m[0]), why: "의존 명사 '수'는 띄어 씁니다 (예: 할 수 있다)." },
  { re: /([가-힣])때(?=[\s,.]|에|는|도|마다|$)/g, fix: (m) => (rieulFinal(m[1]) && m[1] !== '을' ? `${m[1]} 때` : m[0]), why: "'-ㄹ 때'의 '때'는 띄어 씁니다 (예: 발표할 때)." },
  { re: /([가-힣]{2,})(는|은|던|할|한)것(?=[이을은도만과으에]|\s|$)/g, fix: (m) => `${m[1]}${m[2]} 것`, why: "의존 명사 '것'은 띄어 씁니다 (예: 하는 것)." },
  // 자주 틀리는 낱말
  { re: /몇일/g, fix: '며칠', why: "'몇 일'이 아니라 '며칠'입니다 (제27항 붙임2)." },
  { re: /어떻해/g, fix: '어떡해', why: "'어떻게 해'의 준말은 '어떡해'입니다." },
  { re: /금새/g, fix: '금세', why: "'금시에'의 준말은 '금세'입니다." },
  { re: /웬지/g, fix: '왠지', why: "'왜인지'의 준말은 '왠지'입니다." },
  { re: /왠만/g, fix: '웬만', why: "'웬만하다'가 표준어입니다." },
  { re: /역활/g, fix: '역할', why: "'역할(役割)'이 맞습니다." },
  { re: /설겆이/g, fix: '설거지', why: "'설거지'가 표준어입니다 (표준어 규정 제17항)." },
  { re: /오랫만/g, fix: '오랜만', why: "'오래간만'의 준말은 '오랜만'입니다." },
  { re: /희안/g, fix: '희한', why: "'희한(稀罕)하다'가 맞습니다." },
  { re: /어의(없|가 없)/g, fix: (m) => `어이${m[1]}`, why: "'어이없다'가 맞습니다." },
  { re: /구지(?=[\s,.]|$)/g, fix: '굳이', why: "'굳이'로 적습니다." },
  { re: /닥달/g, fix: '닦달', why: "'닦달하다'가 맞습니다." },
  { re: /바램(?=[이을은도]|\s|$)/g, fix: '바람', why: "'바라다'의 명사형은 '바람'입니다." },
  { re: /익숙치/g, fix: '익숙지', why: "'익숙하지'의 준말은 '익숙지'입니다 (제40항)." },
  { re: /생각컨대/g, fix: '생각건대', why: "'생각하건대'의 준말은 '생각건대'입니다 (제40항)." },
  { re: /(일일|깨끗|곰곰|틈틈|번번|따뜻|빽빽)히/g, fix: (m) => `${m[1]}이`, why: "'-이'로 적는 부사입니다 (제51항)." },
  { re: /(꼼꼼|솔직|급|조용|무심)이(?=[\s,.]|$)/g, fix: (m) => `${m[1]}히`, why: "'-히'로 적는 부사입니다 (제51항)." },
  { re: /몇\s?백만/g, fix: '몇백만', why: "수를 나타내는 '몇'은 붙여 씁니다." },
];

export interface KoIssue {
  start: number;
  end: number;
  found: string;
  fix: string;
  why: string;
}

/** 문단 글자에서 규칙 위반 찾기 (겹치면 앞의 것만) */
export function checkKorean(text: string): KoIssue[] {
  const out: KoIssue[] = [];
  for (const r of KO_RULES) {
    r.re.lastIndex = 0;
    let m: RegExpExecArray | null;
    while ((m = r.re.exec(text))) {
      const fix = typeof r.fix === 'string' ? r.fix : r.fix(m);
      if (fix !== m[0]) out.push({ start: m.index, end: m.index + m[0].length, found: m[0], fix, why: r.why });
      if (m[0].length === 0) r.re.lastIndex++;
    }
  }
  out.sort((a, b) => a.start - b.start);
  return out.filter((x, i) => i === 0 || x.start >= out[i - 1].end);
}
